// Regenerates seed.js (the sample data the page shows before a Google Sheet is connected)
// from the seed rows in apps-script.js, so the two never drift apart.
// Run from the repo root: node tools/make-seed.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'apps-script.js'), 'utf8') +
  '\n;this.out = { HOUSING_HEADERS, HOUSING_SEED, DINING_HEADERS, DINING_SEED, COSTS_HEADERS, COSTS_SEED };', ctx);
const s = ctx.out;
const toObjects = (headers, rows) => rows.map((r) => Object.fromEntries(headers.map((h, i) => [h, r[i]])));
const data = {
  housing: toObjects(s.HOUSING_HEADERS, s.HOUSING_SEED),
  dining: toObjects(s.DINING_HEADERS, s.DINING_SEED),
  costs: toObjects(s.COSTS_HEADERS, s.COSTS_SEED),
  reviews: []
};
fs.writeFileSync(path.join(root, 'seed.js'),
  '// Sample data shown until a Google Sheet is connected. Generated by tools/make-seed.js from apps-script.js; do not edit by hand.\n' +
  `const SEED = ${JSON.stringify(data, null, 2)};\n`);
console.log(`seed.js: ${data.housing.length} housing, ${data.dining.length} dining, ${data.costs.length} costs`);
